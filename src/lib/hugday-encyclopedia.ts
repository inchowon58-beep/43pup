function fallbackEncyclopedia(site: HugdaySite): BreedEncyclopedia {
  const page = buildHugdayPage(site);
  return {
    origin: site.tag,
    paragraphs: page.essay,
    genetics: page.notes.map((n) => ({ name: n.title, detail: n.body })),
    care: page.flow.slice(0, 3).map((f) => ({ name: f.title, detail: f.body })),
    beginner: page.lead,
  };
}

export function getEncyclopedia(site: HugdaySite): BreedEncyclopedia {
  return ENCYCLOPEDIA[site.folder] || DOG_ENCYCLOPEDIA[site.folder] || fallbackEncyclopedia(site);
}
